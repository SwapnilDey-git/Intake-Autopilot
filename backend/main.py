async def _questionnaire_covers(form_id: int, doc_type: str) -> bool:
    """True when this supporting doc would only source fields the client's
    questionnaire already answered (same year; identity fields from any year)."""
    allow = DOC_FIELD_ALLOWLIST.get(doc_type)
    if doc_type not in _Q_SKIPPABLE or not allow:
        return False
    f = await database.fetch_one(
        "SELECT client_id, doc_year, case_id FROM forms WHERE id = :id", {"id": form_id})
    if not f or not f["client_id"]:
        return False
    year = f["doc_year"] or await _case_year_hint(f["case_id"], exclude_form_id=form_id)
    rows = await database.fetch_all(
        """SELECT f.doc_year, e.json_result FROM forms f JOIN extractions e ON e.form_id = f.id
           WHERE f.client_id = :c AND f.doc_type = 'intake_sheet' AND f.filename LIKE :p""",
        {"c": f["client_id"], "p": f"{_Q_PREFIX}%"},
    )
    have = set()
    for r in rows:
        jr = r["json_result"]
        jr = json.loads(jr) if isinstance(jr, str) else (jr or {})
        for k, v in jr.items():
            if k in _Q_FIELDS and v not in UNMAPPED_VALUES and (r["doc_year"] == year or k in _IDENTITY_FIELDS):
                have.add(k)
    return allow <= have


@app.post("/api/intake/case")
async def intake_case(payload: IntakeCasePayload, background_tasks: BackgroundTasks):
    """Ingest a whole multi-file submission as one case. Idempotent on
    external_ref (Gmail message id) so a re-polled email doesn't duplicate a
    case. Classifies attachments, drops junk, files supporting docs, and queues
    background extraction of the primary form(s). Returns immediately.

    JSON body: {source, external_ref, sender, subject, files:[{filename, mime,
    content_base64}]} -- an n8n Code node assembles this from the email's binary
    attachments, so the whole Gmail branch is a single Code+HTTP pair."""
    if not database.is_connected:
        return {"success": False, "error": "database not connected"}

    try:
        return await _ingest_case(payload, background_tasks)
    except Exception as e:
        logger.exception("intake_case failed")
        return {"success": False, "error": str(e)}


async def _ingest_case(payload: "IntakeCasePayload", background_tasks: BackgroundTasks):
    source = payload.source
    external_ref = payload.external_ref
    sender = payload.sender
    subject = payload.subject

    # Create-or-fetch the case (external_ref unique). DO UPDATE (not DO NOTHING)
    # so RETURNING yields the id whether the row is new or pre-existing. The
    # conflict target must repeat the partial index's WHERE predicate, otherwise
    # Postgres can't match it to the partial unique index on external_ref.
    if external_ref:
        case_row = await database.fetch_one(
            """INSERT INTO cases (source, external_ref, sender, subject)
               VALUES (:source, :ref, :sender, :subject)
               ON CONFLICT (external_ref) WHERE external_ref IS NOT NULL
               DO UPDATE SET sender = EXCLUDED.sender
               RETURNING id, status""",
            {"source": source, "ref": external_ref, "sender": sender, "subject": subject},
        )
    else:
        case_row = await database.fetch_one(
            "INSERT INTO cases (source, sender, subject) VALUES (:source, :sender, :subject) RETURNING id, status",
            {"source": source, "sender": sender, "subject": subject},
        )
    case_id = case_row["id"]
    # If this exact email was already ingested (case has attachments), don't
    # re-ingest -- Gmail can re-deliver the same message id across polls.
    already = await database.fetch_one(
        "SELECT COUNT(*) AS n FROM forms WHERE case_id = :cid", {"cid": case_id}
    )
    if already and already["n"] > 0:
        return {"success": True, "case_id": case_id, "skipped": "already ingested"}

    # Route this submission to a client (person). Live channels route by sender
    # identity; the folder importer passes client_name. May be None -> the case
    # stays unbound for manual assignment. (ADR-0001)
    client_id = await _match_or_create_client(sender, payload.client_name)
    if client_id:
        await database.execute(
            "UPDATE cases SET client_id = :c WHERE id = :id", {"c": client_id, "id": case_id}
        )

    # Decode every attachment and classify the set (junk dropped, roles + vision
    # fallback assigned). A single undecodable file is skipped, not fatal.
    atts = []
    for f in payload.files:
        b64 = f.content_base64.split(",", 1)[1] if "," in f.content_base64 else f.content_base64
        try:
            content = base64.b64decode(b64)
        except Exception:
            logger.warning(f"Skipping undecodable attachment '{f.filename}' in case ingest.")
            continue
        atts.append({
            "filename": f.filename or "attachment",
            "mime": f.mime,
            "size_bytes": len(content),
            "_content": content,
        })
    # Returned questionnaire PDFs carry their answers in metadata -- store them
    # exactly (no model), and let their ref/name route the case when the sender
    # is unknown. Taken out BEFORE classification so a lone questionnaire PDF is
    # never promoted to a vision-extracted "primary".
    q_atts = [a for a in atts if a["filename"].lower().endswith(".pdf") or a["_content"][:4] == b"%PDF"]
    for a in q_atts:
        data = read_questionnaire_pdf(a["_content"])
        if not data:
            continue
        atts.remove(a)
        sub = QuestionnairePayload(
            client_id=client_id, year=data.get("year"), fields=data.get("fields") or {},
            answers=data.get("answers") or {}, flags=data.get("flags") or [],
            questions=data.get("questions") or [], ref=(str(data.get("ref") or "")[:24] or None),
        )
        res = await _store_questionnaire(sub, pdf=a["_content"], case_id=case_id)
        if res.get("success") and not client_id:
            client_id = res["client_id"]
            await database.execute(
                "UPDATE cases SET client_id = :c WHERE id = :id", {"c": client_id, "id": case_id})
            if sender:  # remember this number/address so her next message routes by itself
                await database.execute(
                    "INSERT INTO client_identities (client_id, kind, value) VALUES (:c, :k, :v) "
                    "ON CONFLICT (kind, value) DO NOTHING",
                    {"c": client_id, "k": _identity_kind(sender), "v": sender.strip().lower()},
                )
    enriched = classify.decide_case_roles(atts)

    primary_jobs = []
    filed_count = 0
    for seq, a in enumerate(enriched):
        content = a["_content"]
        stored_name = _safe_stored_name(case_id, seq, a.get("filename", ""), content)
        (STORAGE_DIR / stored_name).write_bytes(content)
        role = a["role"]
        form_status = "uploaded" if role == "primary" else "supporting"
        # Bind the doc to a person-year: doc_year is the trusted filename year
        # (None for photos); tax_year_id links to the (client, year) row when
        # both the client and a trusted year are known. (ADR-0001)
        doc_year = a.get("year")
        tax_year_id = None
        if client_id and doc_year:
            tax_year_id = await _ensure_tax_year(client_id, doc_year)
        # NB: avoid a bind-param literally named 'fn' -- it collides with the
        # 'fn' argument of SQLAlchemy's @_generative decorator inside the
        # `databases` layer ("multiple values for argument 'fn'").
        form_row = await database.fetch_one(
            "INSERT INTO forms (filename, status, case_id, doc_type, role, client_id, tax_year_id, doc_year) "
            "VALUES (:p_filename, :p_status, :p_case_id, :p_doctype, :p_role, :p_client, :p_taxyear, :p_docyear) RETURNING id",
            {"p_filename": stored_name, "p_status": form_status, "p_case_id": case_id, "p_doctype": a.get("doc_type"),
             "p_role": role, "p_client": client_id, "p_taxyear": tax_year_id, "p_docyear": doc_year},
        )
        form_id = form_row["id"]
        filed_count += 1
        if a.get("extract"):
            primary_jobs.append({"form_id": form_id, "stored_name": stored_name, "content": content})

    await database.execute(
        "INSERT INTO audit_log (form_id, event_type, actor, details) VALUES (NULL, 'case_received', 'n8n-gmail', :d)",
        {"d": json.dumps({"case_id": case_id, "source": source, "documents": filed_count, "primaries": len(primary_jobs)})},
    )

    # Extract primaries off the request path so n8n returns immediately.
    if primary_jobs:
        background_tasks.add_task(_extract_primaries, case_id, primary_jobs)

    return {"success": True, "case_id": case_id, "documents": filed_count, "primaries": len(primary_jobs)}


