# per (client, year) -- a forms row + an extractions row written WITHOUT any
# model -- so the per-year merge picks it up through the existing per-field
# authority (_FIELD_AUTHORITY already ranks intake_sheet first for name, address,
# hometown, marital_status, children). A printable copy lands in the client folder.
QUESTIONNAIRE_PATH = Path(__file__).parent / "static" / "fragebogen.html"
_Q_PREFIX = "fragebogen"
_Q_FIELDS = {
    "name", "e_card_number", "stnr", "tel", "email", "address_austria", "hometown",
    "marital_status", "spouse", "children", "travel_distance_km", "trip_count",
}

# Supporting docs that exist only to source fields the questionnaire also asks
# for (DOC_FIELD_ALLOWLIST). When the client's questionnaire already answered all
# of a doc's fields, extracting it would only re-derive them -- skip the model.
# Money-bearing docs (honorar/svs/E-forms) are never skipped: those figures must
# come from documents, not self-reported answers.
_Q_SKIPPABLE = {"e9", "fambh", "bescheid", "vcf"}


class QuestionnairePayload(BaseModel):
    client_id: int | None = None
    year: int | None = None
    fields: dict = {}
    answers: dict = {}
    flags: list = []
    questions: list = []
    ref: str | None = None
    sheet_text: str | None = None


def _clean_q_fields(raw: dict) -> dict:
    """Keep only known EA fields, trimmed; normalize the numeric/ID ones."""
    out = {}
    for k, v in (raw or {}).items():
        if k not in _Q_FIELDS or v is None:
            continue
        v = str(v).strip()[:255]
        if not v:
            continue
        if k == "e_card_number":
            v = re.sub(r"\D", "", v)
            if len(v) != 10:
                continue
        elif k in ("children", "trip_count"):
            n = _to_number(v)
            if n is None:
                continue
            v = str(int(n))
        elif k == "travel_distance_km":
            n = _to_number(v)
            if n is None:
                continue
            v = str(int(n)) if float(n).is_integer() else str(n)
        out[k] = v
    return out


