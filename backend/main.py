async def _store_questionnaire(payload: QuestionnairePayload, pdf: bytes | None = None,
                               case_id: int | None = None) -> dict:
    """Store a questionnaire submission as the (client, year)'s intake_sheet
    source, file a copy into the client folder, and re-merge the year.
    Resubmitting the same year replaces the previous answers in place. `pdf` is
    the client's returned PDF (public mode) -- kept as the document itself;
    without it a printable HTML copy is rendered."""
    invite = None
    if payload.ref:
        invite = await database.fetch_one(
            "SELECT ref, client_id, year FROM questionnaire_invites WHERE ref = :r", {"r": payload.ref})
        if invite and not payload.client_id:
            payload.client_id = invite["client_id"]
    year = payload.year or _year_from_value((payload.fields or {}).get("year")) or (invite["year"] if invite else None)
    if not year:
        return {"success": False, "error": "year is required"}
    fields = _clean_q_fields(payload.fields)

    client_id = payload.client_id
    if client_id:
        if not await database.fetch_one("SELECT id FROM clients WHERE id = :id", {"id": client_id}):
            raise HTTPException(status_code=404, detail="client not found")
    else:
        # Opened without a client link: route like any other intake -- known
        # email/phone first, else by name (creates the client when new).
        client_id = await _match_or_create_client(fields.get("email") or fields.get("tel"), fields.get("name"))
        if not client_id:
            return {"success": False, "error": "name is required"}
    for kind_val in (fields.get("email"), fields.get("tel")):
        if kind_val:
            await database.execute(
                "INSERT INTO client_identities (client_id, kind, value) VALUES (:c, :k, :v) "
                "ON CONFLICT (kind, value) DO NOTHING",
                {"c": client_id, "k": _identity_kind(kind_val), "v": kind_val.lower()},
            )
    client = await database.fetch_one("SELECT display_name FROM clients WHERE id = :id", {"id": client_id})
    display_name = client["display_name"] or fields.get("name") or f"client{client_id}"

    ty_id = await _ensure_tax_year(client_id, year)
    ext = "pdf" if pdf else "html"
    page = _questionnaire_html(display_name, year, fields, payload)
    stored = f"{_Q_PREFIX}_{client_id}_{year}{_STORED_SEP}Fragebogen_{year}.{ext}"
    if pdf:
        (STORAGE_DIR / stored).write_bytes(pdf)
    else:
        (STORAGE_DIR / stored).write_text(page, encoding="utf-8")

    result = dict(fields)
    result["_answers"] = payload.answers or {}
    result["_flags"] = payload.flags or []
    result["_questions"] = payload.questions or []
    result["_ref"] = payload.ref

    existing = await _questionnaire_row(client_id, year)
    if existing:
        form_id = existing["id"]
        await database.execute(
            "UPDATE forms SET filename = :fn_, status = 'extracted', tax_year_id = :t, created_at = NOW() WHERE id = :id",
            {"fn_": stored, "t": ty_id, "id": form_id},
        )
    else:
        if case_id is None:
            case_row = await database.fetch_one(
                # status 'filed': self-reported answers, not a review item for the legacy case queue
                "INSERT INTO cases (source, client_id, subject, status) VALUES ('fragebogen', :c, :s, 'filed') RETURNING id",
                {"c": client_id, "s": f"Fragebogen {year}"},
            )
            case_id = case_row["id"]
        form_row = await database.fetch_one(
            "INSERT INTO forms (filename, status, case_id, doc_type, role, client_id, tax_year_id, doc_year) "
            "VALUES (:p_filename, 'extracted', :p_case, 'intake_sheet', 'supporting', :p_client, :p_ty, :p_year) RETURNING id",
            {"p_filename": stored, "p_case": case_id, "p_client": client_id, "p_ty": ty_id, "p_year": year},
        )
        form_id = form_row["id"]
    await database.execute("DELETE FROM extractions WHERE form_id = :id", {"id": form_id})
    await database.execute(
        "INSERT INTO extractions (form_id, json_result, confidence) VALUES (:id, :j, :c)",
        {"id": form_id, "j": json.dumps(result), "c": json.dumps({})},
    )

    # Client folder: printable sheet + raw answers next to the year's EA.
    client_dir = CLIENTS_DIR / build_client_folder_name(display_name, str(year))
    client_dir.mkdir(parents=True, exist_ok=True)
    if pdf:
        (client_dir / f"Fragebogen_{year}.pdf").write_bytes(pdf)
    else:
        (client_dir / f"Fragebogen_{year}.html").write_text(page, encoding="utf-8")
    (client_dir / f"Fragebogen_{year}.json").write_text(
        json.dumps({"year": year, **result}, ensure_ascii=False, indent=2), encoding="utf-8")

    await database.execute(
        "INSERT INTO audit_log (form_id, event_type, actor, details) VALUES (:id, 'questionnaire', 'client', :d)",
        {"id": form_id, "d": json.dumps({"client_id": client_id, "year": year, "ref": payload.ref,
                                         "via": "pdf" if pdf else "direct", "fields": sorted(fields)})},
    )
    if payload.ref:
        # Track by ref: a known invite flips to returned; a ref the office never
        # issued (generic link) is recorded so it is still traceable.
        await database.execute(
            """INSERT INTO questionnaire_invites (ref, client_id, year, returned_at, form_id)
               VALUES (:r, :c, :y, NOW(), :f)
               ON CONFLICT (ref) DO UPDATE SET returned_at = NOW(), form_id = EXCLUDED.form_id""",
            {"r": payload.ref[:24], "c": client_id, "y": year, "f": form_id},
        )
    await _rebuild_year_record(client_id, year)
    return {"success": True, "client_id": client_id, "tax_year_id": ty_id, "form_id": form_id,
            "fields_received": sorted(fields)}


# Public copy of the form (Vercel, PUBLIC_FORM_URL): it stores nothing. The
# client gets a PDF whose metadata carries the answers ("STEUERMAPPE1:" +
# base64 JSON in /Keywords) and sends it by WhatsApp/email like any document;
# intake recognizes it below and stores it exactly -- no model involved.
PUBLIC_FORM_URL = os.environ.get("PUBLIC_FORM_URL", "https://steuermappe-fragebogen.vercel.app").rstrip("/")
_Q_PDF_MARK = "STEUERMAPPE1:"
_REF_ALPHABET = "ABCDEFGHJKMNPQRSTUVWXYZ23456789"  # no 0/O/1/I/L -- read aloud on the phone


def read_questionnaire_pdf(content: bytes) -> dict | None:
    """The answers embedded in a Steuermappe PDF, or None for any other file.
    Reads PDF metadata only."""
    if not content.startswith(b"%PDF") or b"STEUERMAPPE1" not in content:
        return None
    try:
        import fitz
        with fitz.open(stream=content, filetype="pdf") as d:
            kw = (d.metadata or {}).get("keywords") or ""
        if not kw.startswith(_Q_PDF_MARK):
            return None
        data = json.loads(base64.b64decode(kw[len(_Q_PDF_MARK):]).decode("utf-8"))
        return data if isinstance(data, dict) else None
    except Exception as e:
        logger.warning(f"questionnaire PDF unreadable: {type(e).__name__}")
        return None


