class ReviewUpdate(BaseModel):
    approved: bool
    updated_data: dict
    reviewer_name: str

# Reisekosten = distance(home -> Vienna) x 2 (round trip) x rate x trips,
# capped at EUR 6,000 (Kennzahl 9160). Distance/trips are reviewer-entered
# for now (no self-hosted geocoding/routing stood up yet).
TRAVEL_RATE_EUR_PER_KM = 0.42
TRAVEL_ROUND_TRIP_FACTOR = 2
TRAVEL_CAP_EUR = 6000

@app.post("/api/forms/{form_id}/review")
async def submit_review(form_id: int, review: ReviewUpdate):
    if not review.reviewer_name or not review.reviewer_name.strip():
        return {"success": False, "error": "reviewer_name is required"}

    if not database.is_connected:
        return {"success": True, "mock": True, "message": "Simulated approval success."}

    try:
        d = review.updated_data
        e_card_number = (d.get("e_card_number") or "").strip() or None
        tax_year = (d.get("tax_year") or "").strip() or None

        if review.approved and e_card_number and tax_year:
            duplicate = await database.fetch_one(
                """
                SELECT id FROM forms
                WHERE status = 'approved' AND e_card_number = :e AND tax_year = :t AND id != :form_id
                """,
                {"e": e_card_number, "t": tax_year, "form_id": form_id},
            )
            if duplicate:
                await database.execute(
                    "INSERT INTO audit_log (form_id, event_type, actor, details) VALUES (:form_id, 'duplicate_blocked', :actor, :details)",
                    {
                        "form_id": form_id,
                        "actor": review.reviewer_name,
                        "details": json.dumps({
                            "conflicting_form_id": duplicate["id"],
                            "e_card_number": e_card_number,
                            "tax_year": tax_year,
                        }),
                    },
                )
                return {
                    "success": False,
                    "reason": "duplicate",
                    "message": f"A form for e-card {e_card_number} / tax year {tax_year} is already approved "
                                f"(form #{duplicate['id']}). Resolve manually before re-approving this one.",
                    "conflicting_form_id": duplicate["id"],
                }

        query = "INSERT INTO reviews (form_id, approved, updated_data, reviewer_name) VALUES (:form_id, :approved, :updated_data, :reviewer_name)"
        values = {
            "form_id": form_id,
            "approved": review.approved,
            "updated_data": json.dumps(d),
            "reviewer_name": review.reviewer_name,
        }
        await database.execute(query=query, values=values)

        status = "approved" if review.approved else "rejected"
        await database.execute(
            "UPDATE forms SET status = :status, e_card_number = :e, tax_year = :t WHERE id = :form_id",
            {"status": status, "e": e_card_number, "t": tax_year, "form_id": form_id},
        )
        # Is this form part of a multi-file case? (NULL for legacy single uploads.)
        case_row = await database.fetch_one(
            "SELECT case_id FROM forms WHERE id = :form_id", {"form_id": form_id}
        )
        case_id = case_row["case_id"] if case_row else None
        await database.execute(
            "INSERT INTO audit_log (form_id, event_type, actor, details) VALUES (:form_id, :event_type, :actor, :details)",
            {
                "form_id": form_id,
                "event_type": "approval" if review.approved else "rejection",
                "actor": review.reviewer_name,
                "details": json.dumps(d),
            },
        )

        # Record the completeness verdict on the reviewer's CURRENT values (not the
        # original extraction) -- so filling a blank in the dashboard before approving
        # is reflected, and the audit trail shows whether an incomplete form was
        # knowingly approved. Warning only; never blocks the approval above.
        completeness = evaluate_completeness(d)
        await database.execute(
            "INSERT INTO audit_log (form_id, event_type, actor, details) VALUES (:form_id, 'completeness', :actor, :details)",
            {
                "form_id": form_id,
                "actor": review.reviewer_name,
                "details": json.dumps(completeness),
            },
        )

        reisekosten = None
        if review.approved:
            try:
                distance_km = float(d.get("travel_distance_km") or 0)
                trip_count = float(d.get("trip_count") or 0)
                reisekosten = round(
                    min(distance_km * TRAVEL_ROUND_TRIP_FACTOR * TRAVEL_RATE_EUR_PER_KM * trip_count, TRAVEL_CAP_EUR),
                    2,
                )
            except (TypeError, ValueError):
                reisekosten = None

            if not EXCEL_TEMPLATE_PATH.exists():
                raise RuntimeError(
                    f"Excel template missing at {EXCEL_TEMPLATE_PATH} — cannot write approval."
                )

            client_folder_name = build_client_folder_name(d.get("name", ""), tax_year or "")
            client_dir = CLIENTS_DIR / client_folder_name
            client_dir.mkdir(parents=True, exist_ok=True)
            year_component = sanitize_path_component(tax_year or "UnknownYear")
            client_xlsx_path = client_dir / f"EA_{year_component}.xlsx"

            if not client_xlsx_path.exists():
                shutil.copy(EXCEL_TEMPLATE_PATH, client_xlsx_path)

            from openpyxl import load_workbook
            wb = load_workbook(client_xlsx_path)
            ws = wb.active
            for field_key, cell_ref in EXCEL_CELL_MAP.items():
                value = d.get(field_key)
                if value not in UNMAPPED_VALUES:
                    ws[cell_ref] = value
            if reisekosten is not None:
                ws[REISEKOSTEN_CELL] = reisekosten
            wb.save(client_xlsx_path)

            excel_path = str(client_xlsx_path)
            await database.execute(
                "INSERT INTO audit_log (form_id, event_type, actor, details) VALUES (:form_id, 'write', :actor, :details)",
                {
                    "form_id": form_id,
                    "actor": review.reviewer_name,
                    "details": json.dumps({"excel_path": excel_path, "reisekosten": reisekosten}),
                },
            )

            # File the original upload alongside the Excel output. Best-effort: a missing
            # source file (e.g. it predates STORAGE_DIR, or was cleaned up) shouldn't block
            # an otherwise-successful approval that already wrote the Excel file above.
            form_row = await database.fetch_one(
                "SELECT filename FROM forms WHERE id = :form_id", {"form_id": form_id}
            )
            source_filename = form_row["filename"] if form_row else None
            if source_filename:
                source_path = STORAGE_DIR / source_filename
                if source_path.exists():
                    content = source_path.read_bytes()
                    original_path = client_dir / f"original_intake{sniff_extension(content)}"
                    shutil.copy(source_path, original_path)
                    await database.execute(
                        "INSERT INTO audit_log (form_id, event_type, actor, details) VALUES (:form_id, 'file', :actor, :details)",
                        {
                            "form_id": form_id,
                            "actor": review.reviewer_name,
                            "details": json.dumps({"original_path": str(original_path)}),
                        },
                    )
                else:
                    logger.warning(f"Source upload missing for form {form_id} at {source_path} — skipping file-filing.")

            # File the rest of the case (Bescheide, invoices, photos, ...) into the
            # same client folder as this primary -- once per case (see filed_dir guard).
            if case_id is not None:
                await _file_case_supporting_docs(case_id, client_dir, review.reviewer_name)

        # Close the case if no primary is left awaiting review (applies to both
        # approve and reject). No-op for legacy forms with no case_id.
        if case_id is not None:
            await _maybe_close_case(case_id)

        return {
            "success": True,
            "status": status,
            "reisekosten": reisekosten,
            "excel_path": excel_path if review.approved else None,
            "completeness": completeness,
        }
    except Exception as e:
        return {"success": False, "error": str(e)}


# Content-type for the raw source doc. Magic-byte sniffing (sniff_extension) is authoritative
# for the formats it knows (pdf/png/jpg) -- the n8n raw-binary path produces extensionless/UUID
# names, so the on-disk extension can't be trusted for those. But it only recognizes three
# formats; for everything else (xlsx is a zip, vcf is plain text) the sniff comes back ".bin"
# and we fall back to the filename extension, which the folder-import path DOES preserve.
_MEDIA_TYPES = {
    ".pdf": "application/pdf",
    ".png": "image/png",
    ".jpg": "image/jpeg",
    ".jpeg": "image/jpeg",
    ".webp": "image/webp",
    ".gif": "image/gif",
    ".xlsx": "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet",
    ".xls": "application/vnd.ms-excel",
    ".csv": "text/csv",
    ".vcf": "text/vcard",
    ".txt": "text/plain",
    ".html": "text/html; charset=utf-8",
    ".bin": "application/octet-stream",
}


@app.get("/api/forms/{form_id}/document")
async def get_form_document(form_id: int):
    """Streams the original uploaded document (PDF/image) for a form so the reviewer
    dashboard can render the real source alongside the AI extraction. ai-service saves
    every upload to STORAGE_DIR/<filename> across all three intake paths, so the source
    for a form_id lives at STORAGE_DIR / forms.filename (same resolution the approval
    file-filing above uses). Read-only; never mutates anything."""
    if not database.is_connected:
        raise HTTPException(status_code=503, detail="Database not connected")

    row = await database.fetch_one(
        "SELECT filename FROM forms WHERE id = :form_id", {"form_id": form_id}
    )
    if not row or not row["filename"]:
        raise HTTPException(status_code=404, detail="Form or filename not found")

    # basename() defends against a stored filename that contains path separators -- the
    # source always lives flat in STORAGE_DIR, so a form can only ever reach its own file.
    source_path = STORAGE_DIR / os.path.basename(row["filename"])
    if not source_path.exists():
        raise HTTPException(status_code=404, detail="Source document not on disk")

    # Magic-byte sniff is authoritative for pdf/png/jpg; when it can't tell (".bin" -- e.g.
    # an xlsx zip or a vcf text file) fall back to the trusted filename extension so the
    # browser gets image/*, the spreadsheet MIME, text/vcard, etc. instead of octet-stream
    # (which the dashboard could only ever show as a broken <img>).
    ext = sniff_extension(source_path.read_bytes())
    if ext == ".bin":
        name_ext = os.path.splitext(row["filename"])[1].lower()
        if name_ext in _MEDIA_TYPES:
            ext = name_ext
    media_type = _MEDIA_TYPES.get(ext, "application/octet-stream")
    # inline so the browser renders it in the iframe instead of downloading it.
    # NOTE: no filename in the header. HTTP header values must be Latin-1, but this
    # client's filenames routinely carry German characters (ä/ö/ü/ß, e.g.
    # "Steuererklärung.pdf") which raise UnicodeEncodeError and 500 the preview. The
    # iframe doesn't need a filename, so we omit it entirely rather than RFC-5987 encode.
    return FileResponse(
        source_path,
        media_type=media_type,
        headers={"Content-Disposition": "inline"},
    )


@app.get("/api/forms/{form_id}/sheet")
async def get_form_sheet(form_id: int):
    """Renders a spreadsheet working-file (.xlsx/.xls) to JSON rows so the dashboard can
    display it inline -- browsers can't render a spreadsheet natively, and the old preview
    just fed it to an <img> and showed a broken image. Reuses the openpyxl the EA write-up
    already depends on (no new dependency, which matters for the airgapped client box).
    Read-only; values only (data_only resolves formulas to their last cached value). Bounded
    to keep the payload sane on a large working file."""
    if not database.is_connected:
        raise HTTPException(status_code=503, detail="Database not connected")

    row = await database.fetch_one(
        "SELECT filename FROM forms WHERE id = :form_id", {"form_id": form_id}
    )
    if not row or not row["filename"]:
        raise HTTPException(status_code=404, detail="Form or filename not found")

    source_path = STORAGE_DIR / os.path.basename(row["filename"])
    if not source_path.exists():
        raise HTTPException(status_code=404, detail="Source document not on disk")
    if source_path.suffix.lower() not in (".xlsx", ".xls"):
        raise HTTPException(status_code=400, detail="Not a spreadsheet")

    MAX_ROWS, MAX_COLS = 300, 40
    from openpyxl import load_workbook

    def _read() -> list[dict]:
        # read_only keeps memory flat on big sheets; data_only gives cached formula results
        # (working files are hand-authored, so cached values are present).
        wb = load_workbook(source_path, data_only=True, read_only=True)
        try:
            out = []
            for ws in wb.worksheets:
                rows, truncated = [], False
                for r, rowcells in enumerate(ws.iter_rows(values_only=True)):
                    if r >= MAX_ROWS:
                        truncated = True
                        break
                    rows.append(["" if c is None else str(c) for c in rowcells[:MAX_COLS]])
                # drop fully-empty trailing rows so the table doesn't render a sea of blanks
                while rows and not any(c.strip() for c in rows[-1]):
                    rows.pop()
                # trim fully-empty trailing columns the same way (working sheets declare a
                # wide A:Z dimension even when only the first few columns carry data).
                width = max((len(r) for r in rows), default=0)
                while width > 0 and not any(len(r) >= width and r[width - 1].strip() for r in rows):
                    width -= 1
                rows = [r[:width] for r in rows]
                # Only a genuine truncation if we hit the cap AND the rows we kept still fill
                # it -- when the trailing trim pulled us back below the cap, the discarded
                # rows were all blank, so the reviewer isn't actually missing anything.
                out.append({"name": ws.title, "rows": rows, "truncated": truncated and len(rows) >= MAX_ROWS})
            return out
        finally:
            wb.close()

    try:
        sheets = await asyncio.to_thread(_read)
    except Exception as e:  # corrupt/unsupported workbook
        raise HTTPException(status_code=422, detail=f"Could not read workbook: {e}")
    return {"sheets": sheets}
