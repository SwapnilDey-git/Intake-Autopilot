async def list_clients():
    """Person-centric queue: one row per client with year/document counts. (ADR-0001)"""
    if not database.is_connected:
        return {"clients": []}
    rows = await database.fetch_all(
        """
        SELECT c.id, c.display_name,
               COUNT(DISTINCT ty.id)  AS year_count,
               COUNT(DISTINCT f.id)   AS doc_count
        FROM clients c
        LEFT JOIN tax_years ty ON ty.client_id = c.id
        LEFT JOIN forms f      ON f.client_id  = c.id
        GROUP BY c.id, c.display_name
        ORDER BY c.display_name
        """
    )
    return {"clients": [dict(r) for r in rows]}


