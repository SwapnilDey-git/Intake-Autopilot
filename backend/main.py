# --- person-centric routing (ADR-0001) -------------------------------------
def _normalize_name(s: str) -> str:
    """Lowercased, diacritics-stripped, whitespace-collapsed key for matching a
    person across submissions ('Popescu Mirela-Maria' -> 'popescu mirela-maria')."""
    s = unicodedata.normalize("NFKD", (s or "").strip())
    s = s.encode("ascii", "ignore").decode("ascii")
    return " ".join(s.lower().split())


def _identity_kind(sender: str) -> str:
    return "email" if sender and "@" in sender else "phone"


async def _match_or_create_client(sender: str | None, client_name: str | None) -> int | None:
    """Route a submission to a client. Order: (1) known sender identity
    (email/phone) -- the reliable signal for live channels; (2) normalized-name
    match; (3) create a new client when we have a name to label it. Returns None
    when there's neither a known sender nor a name -> the case is left unbound
    for manual assignment in the dashboard (person-matching = 'sender, else manual')."""
    sender = (sender or "").strip()
    # 1. sender identity
    if sender:
        found = await database.fetch_one(
            "SELECT client_id FROM client_identities WHERE kind = :k AND value = :v",
            {"k": _identity_kind(sender), "v": sender.lower()},
        )
        if found and found["client_id"]:
            if client_name:
                await database.execute(
                    "UPDATE clients SET display_name = COALESCE(display_name, :n) WHERE id = :id",
                    {"n": client_name.strip()[:255], "id": found["client_id"]},
                )
            return found["client_id"]

    # 2. normalized-name match / 3. create
    norm = _normalize_name(client_name) if client_name else ""
    client_id = None
    if norm:
        row = await database.fetch_one(
            "SELECT id FROM clients WHERE normalized_name = :n ORDER BY id LIMIT 1", {"n": norm}
        )
        client_id = row["id"] if row else None
        if client_id is None:
            row = await database.fetch_one(
                "INSERT INTO clients (display_name, normalized_name) VALUES (:d, :n) RETURNING id",
                {"d": (client_name or "").strip()[:255], "n": norm},
            )
            client_id = row["id"]

    # bind the sender identity to the resolved client for future routing
    if client_id and sender:
        await database.execute(
            "INSERT INTO client_identities (client_id, kind, value) VALUES (:c, :k, :v) "
            "ON CONFLICT (kind, value) DO NOTHING",
            {"c": client_id, "k": _identity_kind(sender), "v": sender.lower()},
        )
    return client_id


async def _case_year_hint(case_id, exclude_form_id=None) -> int | None:
    """The tax year a case is 'about', for binding an undated support doc (e.g. an
    SVS statement whose filename carries no year). Prefer the year of a primary form
    in the same case; else the most common doc_year among the case's dated forms."""
    if not case_id:
        return None
    row = await database.fetch_one(
        """SELECT doc_year FROM forms
           WHERE case_id = :c AND doc_year IS NOT NULL AND id != :ex
           GROUP BY doc_year, role
           ORDER BY (role = 'primary') DESC, count(*) DESC, doc_year DESC
           LIMIT 1""",
        {"c": case_id, "ex": exclude_form_id or -1},
    )
    return row["doc_year"] if row else None


async def _ensure_tax_year(client_id: int, year: int) -> int:
    """Upsert the (client, year) row and return its id."""
    row = await database.fetch_one(
        "INSERT INTO tax_years (client_id, year) VALUES (:c, :y) "
        "ON CONFLICT (client_id, year) DO UPDATE SET client_id = EXCLUDED.client_id "
        "RETURNING id",
        {"c": client_id, "y": year},
    )
    return row["id"]


