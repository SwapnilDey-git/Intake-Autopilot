def _parse_json_result(raw):
    """extractions.json_result comes back as a dict (JSONB) or a JSON string
    depending on the driver/insert path -- normalize to dict-or-None."""
    if isinstance(raw, str):
        try:
            return json.loads(raw)
        except json.JSONDecodeError:
            return None
    return raw if isinstance(raw, dict) else None


