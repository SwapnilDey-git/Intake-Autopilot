@app.post("/api/tax-years/{ty_id}/generate")
async def generate_tax_year_ea(ty_id: int, payload: TaxYearGenerate):
    """Write EA_{year}.xlsx for a client-year from the canonical template using
    the reviewer-confirmed figures. Regenerates fresh each call (idempotent);
    the sheet's formulas compute Aufwand/Gewinn/Grundfreibetrag/Einkünfte."""
    if not payload.reviewer_name or not payload.reviewer_name.strip():
        return {"success": False, "error": "reviewer_name is required"}
    if not database.is_connected:
        return {"success": False, "error": "database not connected"}
    ty = await database.fetch_one(
        """SELECT ty.id, ty.year, c.id AS client_id, c.display_name
           FROM tax_years ty JOIN clients c ON c.id = ty.client_id WHERE ty.id = :id""",
        {"id": ty_id},
    )
    if not ty:
        raise HTTPException(status_code=404, detail="tax year not found")

    d = dict(payload.fields or {})
    year = str(ty["year"])
    d["year"] = year

    # Reisekosten from the confirmed distance/trips (same formula as the EA sheets).
    distance_km = _to_number(d.get("travel_distance_km")) or 0
    trip_count = _to_number(d.get("trip_count")) or 0
    reisekosten = round(
        min(distance_km * TRAVEL_ROUND_TRIP_FACTOR * TRAVEL_RATE_EUR_PER_KM * trip_count, TRAVEL_CAP_EUR), 2
    ) if (distance_km and trip_count) else None
    # No distance/trips confirmed -> the Reisekosten (KZ 9160) printed on the
    # filed E1a, if one was read, so a re-filed year still adds up.
    if reisekosten is None:
        reisekosten = _to_number(d.get("reisekosten"))

    if not EXCEL_TEMPLATE_PATH.exists():
        raise HTTPException(status_code=500, detail=f"Excel template missing at {EXCEL_TEMPLATE_PATH}")

    folder = build_client_folder_name(ty["display_name"] or d.get("name", "") or f"client{ty['client_id']}", year)
    client_dir = CLIENTS_DIR / folder
    client_dir.mkdir(parents=True, exist_ok=True)
    dest = client_dir / f"EA_{sanitize_path_component(year)}.xlsx"
    shutil.copy(EXCEL_TEMPLATE_PATH, dest)

    from openpyxl import load_workbook
    wb = load_workbook(dest)
    ws = wb.active
    for field_key, cell_ref in EA_RECORD_CELL_MAP.items():
        value = d.get(field_key)
        if value in UNMAPPED_VALUES:
            continue
        if field_key in _EA_NUMERIC_FIELDS:
            num = _to_number(value)
            if num is not None:
                ws[cell_ref] = num
            continue
        ws[cell_ref] = value
    if reisekosten is not None:
        ws[REISEKOSTEN_CELL] = reisekosten
    wb.save(dest)

    await database.execute(
        "UPDATE tax_years SET ea_fields = :f, status = 'generated', ea_path = :p WHERE id = :id",
        {"f": json.dumps({"fields": {k: {"value": v} for k, v in d.items()}}), "p": str(dest), "id": ty_id},
    )
    await database.execute(
        "INSERT INTO audit_log (form_id, event_type, actor, details) VALUES (NULL, 'write', :a, :dt)",
        {"a": payload.reviewer_name, "dt": json.dumps({"tax_year_id": ty_id, "ea_path": str(dest), "reisekosten": reisekosten})},
    )
    return {"success": True, "ea_path": str(dest), "reisekosten": reisekosten}


