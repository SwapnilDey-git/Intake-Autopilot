def _to_number(v):
    """Parse a money/count value (accepts de-DE '1.234,50', en '1,234.50', plain
    '2000') to float, or None if it isn't numeric."""
    if v is None or v == "":
        return None
    if isinstance(v, (int, float)):
        return v
    s = re.sub(r"[^\d,.\-]", "", str(v).strip())
    if not s:
        return None
    if "," in s:  # comma present -> treat as the decimal sep, dots are thousands
        s = s.replace(".", "").replace(",", ".")
    try:
        return float(s)
    except ValueError:
        return None

# doc-type trustworthiness, most authoritative first: business figures + identity
# read best off the E-forms; certificates/notices back them up; photos last.
# This is the GENERAL fallback ordering; per-field authority (below) overrides it
# for fields whose authoritative source is a specific document (ticket 02 matrix).
_DOCTYPE_RANK = [
    "e1a", "e1", "steuererklaerung", "l1k", "honorar", "svs", "fambh",
    "bescheid", "steuerkonto", "photo_form", "pdf_form", "working_file", "other", "photo",
]


def _doctype_rank(dt) -> int:
    try:
        return _DOCTYPE_RANK.index(dt)
    except ValueError:
        return len(_DOCTYPE_RANK)


# Per-field authority (perfect-extraction ticket 02 field->source matrix). For each
# EA field, the doc types that source it, MOST authoritative first. This exists
# because a field can now appear on several docs at once -- e.g. svs_sva is the
# authoritative figure on the SVS statement but also a cross-check on the E1a
# widget-join; income/provisionen are authoritative on the Honorar but cross-checked
# on the E-forms. Global doc-type rank would wrongly let the E1a cross-check beat the
# SVS/Honorar source (e1a outranks svs/honorar in _DOCTYPE_RANK), so these fields get
# their own ordering. Fields not listed here fall back to _DOCTYPE_RANK.
_FIELD_AUTHORITY = {
    "stnr":          ["e1", "e1a", "l1k", "steuererklaerung", "bescheid"],
    "e_card_number": ["l1k", "e1", "e1a", "intake_sheet"],
    "name":          ["intake_sheet", "e1", "e1a", "l1k", "steuererklaerung", "bescheid"],
    "address_austria": ["intake_sheet", "e1", "e1a", "steuererklaerung", "bescheid"],
    "hometown":      ["intake_sheet"],
    "tel":           ["vcf", "intake_sheet"],
    "email":         ["vcf", "intake_sheet"],
    "honorare":      ["honorar", "e1a", "e1", "steuererklaerung"],
    "provisionen":   ["honorar", "e1a", "e1", "steuererklaerung"],
    "svs_sva":       ["svs", "e1a", "e1", "steuererklaerung"],
    "reisekosten":   ["e1a", "steuererklaerung"],
    "marital_status": ["intake_sheet", "e9"],
    "spouse":        ["e9", "intake_sheet"],
    "children":      ["intake_sheet", "fambh"],
}


# A supporting doc that falls back to the VISION lane is run through the generic
# handwritten-intake prompt (ai-service /extract), which emits the full 12-field set
# -- meaningless for a fee note or an SVS statement (it will hallucinate name /
# children / marital_status off a document that has none). Confine each lane-3
# supporting doc type to ONLY the EA fields it authoritatively carries, so those
# spurious fields never reach the merged record. Doc types not listed here (the
# E-forms, the intake sheet, photos) may contribute any field.
DOC_FIELD_ALLOWLIST = {
    "honorar": {"honorare", "provisionen"},
    "svs": {"svs_sva"},
    # vCard contact card -> only the two contact fields it authoritatively carries.
    "vcf": {"tel", "email"},
    # E9 spouse certificate -> spouse identity only (it carries no Familienstand string).
    "e9": {"spouse"},
    # Familienbeihilfe notice -> children only.
    "fambh": {"children"},
    # Bescheid is addressed to the taxpayer -> its header is a trustworthy identity
    # source (name + Austrian address + stnr), but nothing else.
    "bescheid": {"stnr", "name", "address_austria"},
}


def _field_rank(ea: str, dt) -> int:
    """Authority of doc type `dt` for EA field `ea` (lower = more authoritative).
    Uses the field's own source order when defined, else the general doc rank; a
    doc type not in a field's list ranks after every listed one (by general rank)."""
    order = _FIELD_AUTHORITY.get(ea)
    if order is None:
        return _doctype_rank(dt)
    try:
        return order.index(dt)
    except ValueError:
        return len(order) + _doctype_rank(dt)


def _year_from_value(v) -> int | None:
    """Pull a 4-digit tax year (2015-2029) out of an extracted tax_year value."""
    m = re.search(r"\b(20(?:1[5-9]|2[0-9]))\b", str(v or ""))
    return int(m.group(1)) if m else None


def _norm_val(v) -> str:
    """Loose equality key so '1.234,50' vs '1234.5', or case/whitespace variance
    in a name, don't register as a conflict."""
    if isinstance(v, (int, float)):
        return str(float(v))
    s = str(v).strip().lower()
    num = re.sub(r"[^\d,.-]", "", s)
    if num and re.fullmatch(r"-?[\d.,]+", num):
        # "1.234,56", "1,234.56", "1234.5" and the model's "1,234,56" are all the
        # same amount: a 1-2 digit tail after the LAST separator is the decimal
        # part, every other separator only groups thousands.
        neg, body = num.startswith("-"), num.lstrip("-")
        m = re.fullmatch(r"(.*)[.,](\d{1,2})", body)
        whole, frac = (m.group(1), m.group(2)) if m else (body, "0")
        try:
            n = float(f"{re.sub(r'[.,]', '', whole) or '0'}.{frac}")
            return str(-n if neg else n)
        except ValueError:
            pass
    return " ".join(s.split())


# ID fields are the SAME value whether written "12 345/6789", "12-345/6789" or
# "123456789" -- compare them on digits alone so format variance across two docs
# doesn't raise a false conflict. (_norm_val mis-handles a slashed id: the interior
# '-'/'/' either breaks the float parse or silently drops separators inconsistently.)
_ID_FIELDS = {"stnr", "e_card_number"}


def _norm_for(ea: str, v) -> str:
    """Field-aware conflict key: digit-only for IDs, else the generic _norm_val."""
    if ea in _ID_FIELDS:
        digits = re.sub(r"\D", "", str(v or ""))
        return digits or _norm_val(v)
    return _norm_val(v)


_MONEY_EA_FIELDS = ("honorare", "svs_sva", "kleinmaterial", "provisionen",
                    "abschreibung", "sonstiger_aufwand", "reisekosten")


def _doc_date(filename, created_at) -> str:
    """Sortable 'YYYYMMDDHHMMSS' age of a document: the PDF's own creation (else
    modification) date when it has one, else when we received it. Used so that of
    two copies of the same form for one year (e.g. the original E1a and the
    corrected one sent with an Ergaenzungsersuchen answer) the newer one wins.
    Reads PDF metadata only -- never page content."""
    try:
        import fitz
        with fitz.open(STORAGE_DIR / os.path.basename(filename or "")) as d:
            m = d.metadata or {}
        for k in ("creationDate", "modDate"):
            digits = re.sub(r"\D", "", m.get(k) or "")[:14]
            if len(digits) >= 8:
                return digits.ljust(14, "0")
    except Exception:
        pass
    return created_at.strftime("%Y%m%d%H%M%S") if created_at else ""


def merge_year_fields(sources: list[dict]) -> dict:
    """Merge many docs' extracted fields into one EA record.

    sources: [{form_id, doc_type, fields, doc_date?}]. Returns {ea_field: {value,
    source_form_id, source_doc_type, conflict, alternatives, superseded}} -- the
    value chosen by PER-FIELD authority (each field's designated source doc wins;
    see _FIELD_AUTHORITY), and among docs of equal authority the NEWEST one
    (doc_date). A differing value from an OLDER copy of the same doc type is a
    superseded version, not a conflict; any other differing candidate is."""
    from collections import defaultdict
    cand = defaultdict(list)
    for s in sources:
        dt = s.get("doc_type") or "other"
        allow = DOC_FIELD_ALLOWLIST.get(dt)
        for k, v in (s.get("fields") or {}).items():
            ea = _EXTRACT_TO_EA.get(k, k)
            if ea not in EA_RECORD_FIELDS:
                continue
            if allow is not None and ea not in allow:
                continue  # a scanned honorar/svs/bescheid may only source its own fields
            if v in UNMAPPED_VALUES or (isinstance(v, str) and not v.strip()):
                continue
            cand[ea].append({"value": v, "doc_type": dt, "form_id": s.get("form_id"),
                             "rank": _field_rank(ea, dt), "date": s.get("doc_date") or ""})
    # A doc whose money lines were read cell-by-cell (ai-service Kennzahl-cell
    # reader marks it with _kz_cells_checked) has KNOWN blanks: an empty line on
    # it is a real "nothing here". An OLDER copy of the same doc type then may not
    # fill that line back in from its own (typically misread) figures.
    complete = {}
    for s in sources:
        if "_kz_cells_checked" in (s.get("fields") or {}):
            dt, dd = s.get("doc_type") or "other", s.get("doc_date") or ""
            complete[dt] = max(complete.get(dt, ""), dd)
    for ea in _MONEY_EA_FIELDS:
        if ea in cand:
            cand[ea] = [c for c in cand[ea] if not (c["doc_type"] in complete and c["date"] < complete[c["doc_type"]])]
            if not cand[ea]:
                del cand[ea]
    out = {}
    for ea, lst in cand.items():
        lst.sort(key=lambda c: c["date"], reverse=True)  # newest first...
        lst.sort(key=lambda c: c["rank"])                 # ...within each authority rank (stable)
        best = lst[0]
        diff = [c for c in lst[1:] if _norm_for(ea, c["value"]) != _norm_for(ea, best["value"])]
        older = [c for c in diff if c["doc_type"] == best["doc_type"] and c["date"] < best["date"]]
        alts = [c for c in diff if c not in older]
        out[ea] = {
            "value": best["value"],
            "source_form_id": best["form_id"],
            "source_doc_type": best["doc_type"],
            "conflict": bool(alts),
            "alternatives": [
                {"value": a["value"], "doc_type": a["doc_type"], "form_id": a["form_id"]} for a in alts
            ],
            "superseded": [
                {"value": a["value"], "doc_type": a["doc_type"], "form_id": a["form_id"]} for a in older
            ],
        }
    return out


# Identity/contact fields that are stable across tax years -- a person's name,
# tax numbers, Austrian address and origin/contact don't change year to year, so a
# year with no source for them may inherit the value from ANY of the person's docs.
# (Year-specific fields -- figures, marital_status, children, spouse -- are NOT here.)
_IDENTITY_FIELDS = ["name", "stnr", "e_card_number", "address_austria", "hometown", "tel", "email"]


async def _client_identity(client_id: int) -> dict:
    """Merge the stable identity fields across ALL of a client's extracted documents
    (every year, every doc). Returns {ea_field: merged_entry} for identity fields only
    -- the person-level view used to backfill a year that lacks its own identity doc."""
    rows = await database.fetch_all(
        """SELECT f.id AS form_id, f.doc_type, f.filename, f.created_at, e.json_result
           FROM forms f JOIN extractions e ON e.form_id = f.id
           WHERE f.client_id = :c""",
        {"c": client_id},
    )
    sources = []
    for r in rows:
        jr = r["json_result"]
        fields = json.loads(jr) if isinstance(jr, str) else (jr or {})
        sources.append({"form_id": r["form_id"], "doc_type": r["doc_type"], "fields": fields,
                        "doc_date": _doc_date(r["filename"], r["created_at"])})
    merged = merge_year_fields(sources)
    return {k: v for k, v in merged.items() if k in _IDENTITY_FIELDS}


async def _rebuild_year_record(client_id: int, year: int) -> int | None:
    """Re-merge all extracted docs for (client, year) into tax_years.ea_fields.
    Always rebuilds, even for years already reviewed/generated, so a later
    extraction fix is reflected no matter how many times the year has been
    processed before. A reviewer's edits live in ea_fields until the next
    rebuild overwrites them with the freshly re-merged sources -- rebuild is
    triggered only by new/re-extracted documents, not by review actions."""
    ty = await database.fetch_one(
        "SELECT id, status FROM tax_years WHERE client_id = :c AND year = :y", {"c": client_id, "y": year}
    )
    if ty is None:
        ty_id = await _ensure_tax_year(client_id, year)
    else:
        ty_id = ty["id"]
    rows = await database.fetch_all(
        """SELECT f.id AS form_id, f.doc_type, f.filename, f.created_at, e.json_result
           FROM forms f JOIN extractions e ON e.form_id = f.id
           WHERE f.client_id = :c AND f.doc_year = :y""",
        {"c": client_id, "y": year},
    )
    sources = []
    for r in rows:
        jr = r["json_result"]
        fields = json.loads(jr) if isinstance(jr, str) else (jr or {})
        sources.append({"form_id": r["form_id"], "doc_type": r["doc_type"], "fields": fields,
                        "doc_date": _doc_date(r["filename"], r["created_at"])})
    merged = merge_year_fields(sources)

    # Children-count fallback: Austrian practice files one L1k per claimed child,
    # so when no FamBH notice / intake sheet gave a children value (FamBH is
    # routinely missing), the number of L1k primaries filed this year is itself
    # a reliable signal. Pure row count -- never opens or reads a document.
    if "children" not in merged:
        l1k_count = await database.fetch_val(
            """SELECT COUNT(*) FROM forms
               WHERE client_id = :c AND doc_year = :y AND doc_type = 'l1k' AND role = 'primary'""",
            {"c": client_id, "y": year},
        )
        if l1k_count:
            merged["children"] = {
                "value": str(l1k_count),
                "source_form_id": None,
                "source_doc_type": "l1k_count",
                "conflict": False,
                "alternatives": [],
            }

    # Person-wide identity backfill: any stable identity field this year has no
    # source for is inherited from the client's OTHER documents (e.g. an address off
    # a prior year's Bescheid). Fills GAPS only -- an in-year value is never overridden
    # -- and marks inherited values so the reviewer knows they came from another doc.
    id_view = await _client_identity(client_id)
    for f in _IDENTITY_FIELDS:
        if f not in merged and f in id_view:
            entry = dict(id_view[f])
            entry["inherited"] = True
            merged[f] = entry

    await database.execute(
        "UPDATE tax_years SET ea_fields = :f WHERE id = :id",
        {"f": json.dumps({"fields": merged}), "id": ty_id},
    )
    return ty_id


